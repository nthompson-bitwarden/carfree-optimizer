#!/usr/bin/env python3
"""E02-S01: deterministically extract the bounded Census pilot (no downloads).

Input archives are acquired separately from the pinned URLs. Output preserves
all KML LinearRing longitude/latitude strings; zero altitude is discarded.
"""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
import zipfile

BASE = "https://www2.census.gov/geo/tiger/GENZ2024/kml/"
SOURCES = [
    ("cb_2024_23_place_500k", "f6960ad20bc755c1054d8d2eb8cbe0d99291436266af7e7014c1531ac23bcd4f", "20b47eacc4215dc1d168c9f6c7ec8497e91d0b1b6b852dc7a87f4ead76749e6a", "2360545", "Portland city", "city", "ME"),
    ("cb_2024_41_place_500k", "b6cd97a27f60e595bef09fba3452302e2d818758b4ede7116c855291cd16251b", "27f98a8072992c41e135c7e10417d3960a81649963b91eab4837962f61a4e35b", "4159000", "Portland city", "city", "OR"),
    ("cb_2024_us_cbsa_500k", "683216b2fc2d2f5593fcd3c3c52b27e1dded0eba9d2efa6e2d259138e95613f4", "87d81896f205042ed7081808d86abd198e557540f6d963710b409d1f13c002e2", "38900", "Portland-Vancouver-Hillsboro, OR-WA Metro Area", "metro", "OR,WA"),
]
NS = {"k": "http://www.opengis.net/kml/2.2"}
LICENSE = "U.S. Census Bureau public domain; attribution requested"
RETRIEVED = "2026-11-17"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def extract(source_dir):
    records = []
    manifest = {"schema": "carfree-geography-source-v1", "vintage": "2024", "retrieved_date": RETRIEVED, "crs": "EPSG:4326", "units": "longitude/latitude degrees", "scale": "1:500000", "license": LICENSE, "sources": []}
    for stem, zip_sha, member_sha, geoid, name, kind, states in SOURCES:
        archive = (source_dir / f"{stem}.zip").read_bytes()
        if digest(archive) != zip_sha:
            raise ValueError(f"{stem}.zip: SHA256 differs from pinned source")
        with zipfile.ZipFile(source_dir / f"{stem}.zip") as bundle:
            raw = bundle.read(f"{stem}.kml")
        if digest(raw) != member_sha:
            raise ValueError(f"{stem}.kml: SHA256 differs from pinned member")
        selected = []
        for area in ET.fromstring(raw).findall(".//k:Placemark", NS):
            attributes = {item.attrib["name"]: item.text for item in area.findall(".//k:SimpleData", NS)}
            if attributes.get("GEOID") == geoid:
                selected.append((area, attributes))
        if len(selected) != 1:
            raise ValueError(f"{stem}: expected exactly one GEOID {geoid}, found {len(selected)}")
        area, attributes = selected[0]
        if attributes.get("NAMELSAD") != name:
            raise ValueError(f"{geoid}: canonical source name differs")
        if kind == "city" and attributes.get("STUSPS") != states:
            raise ValueError(f"{geoid}: source state differs")
        if kind == "metro" and (attributes.get("LSAD") != "M1" or not name.endswith("OR-WA Metro Area")):
            raise ValueError(f"{geoid}: expected metropolitan area and selected state suffix")
        identifier = f"{'place' if kind == 'city' else 'cbsa'}:{geoid}"
        lines = ["\t".join(["area", identifier, kind, name, states, BASE + stem + ".zip", "2024", RETRIEVED, LICENSE])]
        ring_lengths = []
        for coordinates in area.findall(".//k:LinearRing/k:coordinates", NS):
            points = []
            for point in (coordinates.text or "").split():
                components = point.split(",")
                if len(components) != 3 or float(components[2]) != 0:
                    raise ValueError(f"{geoid}: expected longitude,latitude,zero-altitude")
                points.append(",".join(components[:2]))
            if len(points) < 4 or points[0] != points[-1]:
                raise ValueError(f"{geoid}: unclosed or short source ring")
            ring_lengths.append(len(points))
            lines.append("ring\t" + "\t".join(points))
        if not ring_lengths:
            raise ValueError(f"{geoid}: missing source boundary")
        records.append((identifier, lines))
        manifest["sources"].append({"id": identifier, "canonical_name": name, "states": states.split(","), "url": BASE + stem + ".zip", "zip_sha256": zip_sha, "member": stem + ".kml", "member_sha256": member_sha, "ring_vertex_counts": ring_lengths})
    content = "carfree-geography-v1\n" + "\n".join(line for _, lines in sorted(records) for line in lines) + "\n"
    manifest["catalogue_sha256"] = digest(content.encode())
    return content, json.dumps(manifest, indent=2, sort_keys=True) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_dir", type=Path)
    parser.add_argument("--output-dir", type=Path, default=Path(__file__).resolve().parents[1] / "fixtures/geography")
    parser.add_argument("--check", action="store_true", help="compare generated bytes with existing artifacts, without writing")
    args = parser.parse_args()
    try:
        catalogue, manifest = extract(args.source_dir)
        files = {"pilot.tsv": catalogue, "sources.json": manifest}
        if args.check:
            for name, content in files.items():
                if (args.output_dir / name).read_bytes() != content.encode():
                    raise ValueError(f"{name}: differs from reproducible source extraction")
        else:
            args.output_dir.mkdir(parents=True, exist_ok=True)
            for name, content in files.items():
                (args.output_dir / name).write_bytes(content.encode())
        print("E02-S01 source extraction verified: 3 canonical areas; original rings retained.")
    except (OSError, ValueError, KeyError, zipfile.BadZipFile, ET.ParseError) as error:
        print(f"Geography source preparation failed: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
